#!/usr/bin/env python3
# Regenerates packages/core/src/patches/fonts/noto-sans-data.ts from static Noto Sans 2.x TTFs (SIL OFL 1.1).
# Usage: python3 scripts/fonts/noto-sans-subset.py <dir with NotoSans-{Regular,Bold,Italic}.ttf>
# Requires fontTools (pip install fonttools). Arch: the noto-fonts package ships the inputs in /usr/share/fonts/noto.
import base64, hashlib, io, pathlib, sys
from fontTools import subset
from fontTools.ttLib import TTFont

# Latin, Latin-1, Latin Extended-A/B, IPA, spacing marks, combining marks, Greek, Cyrillic, Latin Extended Additional,
# punctuation, currency, letterlike, number forms, arrows, minus, geometric shapes, ligatures, BOM, replacement character.
UNICODES = 'U+0000-052F,U+1E00-1EFF,U+2000-206F,U+20A0-20CF,U+2100-215F,U+2190-21FF,U+2212,U+25A0-25FF,U+FB00-FB06,U+FEFF,U+FFFD'
STYLES = ['Regular', 'Bold', 'Italic']
OUT = pathlib.Path(__file__).resolve().parents[2] / 'packages/core/src/patches/fonts/noto-sans-data.ts'


def build(src: pathlib.Path) -> bytes:
    opts = subset.Options()
    opts.hinting = False
    opts.name_IDs = ['*']
    opts.name_languages = ['*']
    opts.drop_tables += ['DSIG']
    font = TTFont(src)
    if 'fvar' in font:
        sys.exit(f'{src} is a variable font; Apportable CoreGraphics needs a static one')
    s = subset.Subsetter(opts)
    s.populate(unicodes=subset.parse_unicodes(UNICODES))
    s.subset(font)
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def main() -> None:
    src = pathlib.Path(sys.argv[1])
    lines = [
        '// GENERATED by scripts/fonts/noto-sans-subset.py - do not edit.',
        '// Noto Sans (static, subset, unhinted). Copyright 2022 The Noto Project Authors',
        '// (https://github.com/notofonts/latin-greek-cyrillic). Licensed under the SIL Open Font License 1.1, see',
        '// packages/core/src/patches/fonts/OFL.txt. Only the font data is OFL; the rest of this project is GPL-3.0-only.',
        '',
    ]
    for style in STYLES:
        data = build(src / f'NotoSans-{style}.ttf')
        lines.append(f'/** NotoSans-{style}.ttf, {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()} */')
        lines.append(f"export const NOTO_SANS_{style.upper()}_B64 =\n  '{base64.b64encode(data).decode()}';")
    OUT.write_text('\n'.join(lines) + '\n')
    print('wrote', OUT)


main()
